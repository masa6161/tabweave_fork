import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

// Chinese resources come exclusively from the configured upstream revision.
// Run `git fetch upstream main` before this script to import newer translations.
const root = resolve(import.meta.dirname, '..')
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' })
const ref = 'upstream/main'
const source = 'https://github.com/zxpzdtom/tabweave'
const remote = git('remote', 'get-url', 'upstream').trim().replace(/\.git$/, '')
if (remote !== source) throw new Error(`Expected upstream ${source}, got ${remote}`)
const revision = git('rev-parse', ref).trim()
const read = (path) => git('show', `${ref}:${path}`)
const i18n = read('src/lib/i18n.ts')
const constants = read('src/lib/constants.ts')
const ai = read('src/lib/ai/grouping.ts')
const zh = i18n.match(/const zh: typeof en = (\{[\s\S]*?\n\})\n/)
const prompt = constants.match(/export const DEFAULT_AI_GROUPING_PROMPT_ZH = (\[[\s\S]*?\]\.join\('\\n'\))/)
const docs = constants.match(/id: 'docs-default',[\s\S]*?pattern: ('[^']*')/)
const title = ai.match(/const exampleTitle = language === 'Chinese' \? ('[^']*')/)
const reason = ai.match(/const exampleReason = language === 'Chinese' \? ('[^']*')/)
if (!zh || !prompt || !docs || !title || !reason) throw new Error('Upstream source format changed; update the importer without editing Chinese copy.')
const names = [...constants.matchAll(/id: '([^']+)',\s*name: '([^']+)'/g)]
  .map(([, id, name]) => `  '${id}': '${name}',`).join('\n')
const generated = `// Generated by scripts/sync-upstream-chinese.mjs. Do not edit Chinese copy.\n// Source: ${source} @ ${revision}\nexport const UPSTREAM_ZH = ${zh[1]}\n\nexport const UPSTREAM_DEFAULT_RULE_NAMES: Record<string, string> = {\n${names}\n}\n\nexport const UPSTREAM_DOCS_PATTERN = ${docs[1]}\n\nexport const UPSTREAM_AI_GROUPING_PROMPT = ${prompt[1]}\n\nexport const UPSTREAM_AI_EXAMPLE = { title: ${title[1]}, reason: ${reason[1]} }\n`
const files = {
  'src/lib/upstream-chinese.ts': generated,
  'public/_locales/zh_CN/messages.json': read('public/_locales/zh_CN/messages.json'),
  'README.zh-CN.md': read('README.zh-CN.md'),
}
const hashes = {}
for (const [path, text] of Object.entries(files)) {
  await mkdir(resolve(root, path, '..'), { recursive: true })
  await writeFile(resolve(root, path), text)
  hashes[path] = createHash('sha256').update(text).digest('hex')
}
await writeFile(resolve(root, 'src/lib/upstream-chinese.json'), JSON.stringify({ source, revision, hashes }, null, 2) + '\n')
console.log(`Imported unchanged Chinese resources from upstream ${revision.slice(0, 7)}.`)
